-- ==========================================
-- 1. CREACIÓN DE TABLAS DE CATEGORÍAS Y UNIDADES
-- ==========================================

CREATE TABLE IF NOT EXISTS public.product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.product_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    abbreviation TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar RLS
ALTER TABLE public.product_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_units ENABLE ROW LEVEL SECURITY;

CREATE POLICY "authenticated_full_access_product_categories" ON public.product_categories FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "authenticated_full_access_product_units" ON public.product_units FOR ALL TO authenticated USING (true) WITH CHECK (true);


-- ==========================================
-- 2. MODIFICACIÓN DE LA TABLA PRODUCTS
-- ==========================================

ALTER TABLE public.products 
ADD COLUMN IF NOT EXISTS category_id BIGINT REFERENCES public.product_categories(id) ON DELETE SET NULL,
ADD COLUMN IF NOT EXISTS unit_id BIGINT REFERENCES public.product_units(id) ON DELETE SET NULL;

-- Migración de datos existentes de "unit" (texto) a "product_units"
INSERT INTO public.product_units (name)
SELECT DISTINCT unit FROM public.products WHERE unit IS NOT NULL AND unit != ''
ON CONFLICT (name) DO NOTHING;

UPDATE public.products p
SET unit_id = pu.id
FROM public.product_units pu
WHERE p.unit = pu.name AND p.unit_id IS NULL;


